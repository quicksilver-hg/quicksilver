def main() -> int:
    stroke_width, primitives = mercury_primitives()
    for icon in HUD_ICONS:
        src_path = SRC_DIR / f"hud_{icon.name}.svg"
        png_path = ICON_DIR / icon.output_png
        src_path.write_text(source_svg(stroke_width, primitives, icon), encoding="utf8")
        subprocess.run(
            ["rsvg-convert", "-w", str(SIZE), "-h", str(SIZE), str(src_path), "-o", str(png_path)],
            check=True,
        )
    print("qt hud icons regenerated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
