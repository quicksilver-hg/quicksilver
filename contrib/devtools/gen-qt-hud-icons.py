from __future__ import annotations

import subprocess
import xml.etree.ElementTree as ET
from dataclasses import dataclass
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
BRAND_SVG = ROOT / "src/qt/res/src/quicksilver.svg"
SRC_DIR = ROOT / "src/qt/res/src"
ICON_DIR = ROOT / "src/qt/res/icons"
SIZE = 128


@dataclass(frozen=True)
class MercuryPrimitive:
    tag: str
    attrs: dict[str, str]


@dataclass(frozen=True)
class HudIcon:
    name: str
    output_png: str
    mercury_scale: float
    mercury_center_x: float
    mercury_center_y: float
    extras: tuple[str, ...]
    include_mercury: bool = True


def strip_namespace(tag: str) -> str:
    return tag.rsplit("}", 1)[-1]


def mercury_primitives() -> tuple[str, list[MercuryPrimitive]]:
    root = ET.parse(BRAND_SVG).getroot()
    knockout = None
    for node in root.iter():
        if strip_namespace(node.tag) == "mask" and node.attrib.get("id") == "mercury-knockout":
            knockout = node
            break
    if knockout is None:
        raise RuntimeError(f"{BRAND_SVG} is missing mask id mercury-knockout")

    mercury_group = None
    for node in knockout:
        if strip_namespace(node.tag) == "g" and node.attrib.get("stroke") == "black":
            mercury_group = node
            break
    if mercury_group is None:
        raise RuntimeError(f"{BRAND_SVG} is missing the Mercury stroke group")

    stroke_width = mercury_group.attrib["stroke-width"]
    primitives: list[MercuryPrimitive] = []
    for child in mercury_group:
        tag = strip_namespace(child.tag)
        if tag not in {"path", "circle", "line"}:
            raise RuntimeError(f"unsupported Mercury primitive: {tag}")
        primitives.append(MercuryPrimitive(tag=tag, attrs=dict(child.attrib)))
    return stroke_width, primitives


def attrs_text(attrs: dict[str, str]) -> str:
    return " ".join(f'{key}="{value}"' for key, value in attrs.items())


def mercury_group_svg(stroke_width: str, primitives: list[MercuryPrimitive], icon: HudIcon) -> str:
    tx = icon.mercury_center_x - (512 * icon.mercury_scale)
    ty = icon.mercury_center_y - (512 * icon.mercury_scale)
    elements = "\n".join(
        f"      <{primitive.tag} {attrs_text(primitive.attrs)}/>"
        for primitive in primitives
    )
    return f"""    <g fill="none" stroke="#000000" stroke-width="{stroke_width}"
       stroke-linecap="round" stroke-linejoin="round"
       transform="translate({tx:.3f} {ty:.3f}) scale({icon.mercury_scale:.3f})">
{elements}
    </g>"""


def source_svg(stroke_width: str, primitives: list[MercuryPrimitive], icon: HudIcon) -> str:
    extras = "\n".join(icon.extras)
    mercury = mercury_group_svg(stroke_width, primitives, icon) if icon.include_mercury else ""
    provenance = (
        "Generated from src/qt/res/src/quicksilver.svg by contrib/devtools/gen-qt-hud-icons.py."
        if icon.include_mercury
        else "Generated by contrib/devtools/gen-qt-hud-icons.py for the Quicksilver HUD icon family."
    )
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!--
  Quicksilver HUD {icon.name} icon.
  {provenance}

  Copyright (c) 2026 The Quicksilver developers
  Distributed under the MIT software license, see the accompanying file COPYING
  or https://opensource.org/license/mit/.
-->
<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}">
  <g fill="none" stroke="#000000" stroke-width="8.5" stroke-linecap="round" stroke-linejoin="round">
{extras}
  </g>
{mercury}
</svg>
"""


